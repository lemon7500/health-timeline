package com.healthtimeline.compatprobe;

import android.app.Activity;
import android.os.Bundle;
import android.util.Log;
import android.widget.TextView;

import androidx.sqlite.db.SupportSQLiteDatabase;
import androidx.sqlite.db.SupportSQLiteOpenHelper;

import java.io.File;
import java.io.PrintWriter;
import java.io.StringWriter;

/** Keeps the old engine's WAL connection alive until the host kills this disposable process. */
public final class SeedActivity extends Activity {
    private SupportSQLiteOpenHelper retainedWalHelper;

    @Override public void onCreate(Bundle state) {
        super.onCreate(state);
        TextView label = new TextView(this);
        setContentView(label);
        label.setText("Creating public synthetic encrypted fixtures on a background worker.");
        new Thread(() -> seed(label), "synthetic-sqlcipher-seed").start();
    }

    private void seed(TextView label) {
        try {
            if (!BuildConfig.FLAVOR.equals("baseline")) throw new IllegalStateException("Only the real old engine may seed fixtures");
            if (new File(getFilesDir(), "seed-ready.json").exists()
                    || getDatabasePath("closed.db").exists() || getDatabasePath("wal.db").exists()) {
                throw new IllegalStateException("Use a fresh disposable emulator; seed must not replace data");
            }
            System.loadLibrary("sqlcipher");
            boolean persisted = getSharedPreferences("synthetic-key", MODE_PRIVATE).edit()
                .putString("public-test-key", ProbeData.PUBLIC_PASSWORD)
                .putString("member-uuid", java.util.UUID.nameUUIDFromBytes("family_members:2".getBytes(java.nio.charset.StandardCharsets.UTF_8)).toString())
                .commit();
            if (!persisted) throw new IllegalStateException("Synthetic key preferences could not be persisted");
            try (SupportSQLiteOpenHelper closed = ProbeData.helper(this, "closed.db")) {
                closed.setWriteAheadLoggingEnabled(true);
                SupportSQLiteDatabase db = closed.getWritableDatabase();
                requireOldEngine(db);
                ProbeData.seed(this, db, "closed-old-engine");
                ProbeData.write(new File(getFilesDir(), "closed.snapshot.json"), ProbeData.snapshot(this, db).toString(2));
            }
            ProbeData.write(new File(getFilesDir(), "closed.sha256"), ProbeData.hash(getDatabasePath("closed.db")));
            retainedWalHelper = ProbeData.helper(this, "wal.db");
            retainedWalHelper.setWriteAheadLoggingEnabled(true);
            SupportSQLiteDatabase wal = retainedWalHelper.getWritableDatabase();
            requireOldEngine(wal);
            // This setter returns a row. SQLCipher rejects result-bearing SQL via
            // execSQL; consume it through query and verify the actual setting.
            String disabledAutoCheckpoint = ProbeData.scalar(wal, "PRAGMA wal_autocheckpoint=0");
            if (!"0".equals(disabledAutoCheckpoint)
                    || !"0".equals(ProbeData.scalar(wal, "PRAGMA wal_autocheckpoint"))) {
                throw new IllegalStateException("Old WAL auto-checkpoint could not be disabled");
            }
            ProbeData.seed(this, wal, "committed-only-in-old-WAL");
            ProbeData.write(new File(getFilesDir(), "wal.snapshot.json"), ProbeData.snapshot(this, wal).toString(2));
            File walFile = new File(getDatabasePath("wal.db").getPath() + "-wal");
            if (walFile.length() <= 32) throw new IllegalStateException("Committed uncheckpointed WAL fixture not created");
            ProbeData.write(new File(getFilesDir(), "seed-ready.json"),
                "{\"baselineArtifact\":\"4.18.0\",\"schemaVersion\":8,\"walBytes\":" + walFile.length() + "}");
            runOnUiThread(() -> label.setText("PUBLIC SYNTHETIC fixture ready. Host must force-stop without closing WAL."));
        } catch (Exception failure) {
            Log.e("SyntheticSQLCompat", "Synthetic seed failed", failure);
            StringWriter trace = new StringWriter();
            failure.printStackTrace(new PrintWriter(trace));
            try { ProbeData.write(new File(getFilesDir(), "seed-error.txt"), trace.toString()); }
            catch (Exception ignored) { }
            runOnUiThread(() -> label.setText("Synthetic seed failed: " + failure));
        }
    }

    private static void requireOldEngine(SupportSQLiteDatabase db) {
        if (!ProbeData.scalar(db, "PRAGMA cipher_version").startsWith("4.18.0")) {
            throw new IllegalStateException("Baseline was not genuinely generated by SQLCipher 4.18.0");
        }
    }

    // Deliberately do not close retainedWalHelper here: the host kills this process to
    // reproduce a committed WAL from an interrupted old app, not a graceful checkpoint.
}

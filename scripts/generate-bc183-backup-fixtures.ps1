param(
    [Parameter(Mandatory = $true)][string]$LegacyBcJar,
    [Parameter(Mandatory = $true)][string]$JdkDirectory
)

$ErrorActionPreference = 'Stop'
$taskRepo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$taskResources = Join-Path $taskRepo 'apps/android/app/src/test/resources/backup-compat'
$taskProbeSource = Join-Path $taskRepo 'apps/android/app/src/test/java/com/healthtimeline/app/backup/LegacyBackupCryptoProbe.java'
$taskLegacyJar = (Resolve-Path -LiteralPath $LegacyBcJar).Path
$taskJdk = (Resolve-Path -LiteralPath $JdkDirectory).Path
$taskExpectedJarHash = '82cf3a2af766c3bc874f6d36b9f20a8b99a8f09762dc776e8a227a45d8daaafb'
if ((Get-FileHash -LiteralPath $taskLegacyJar -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskExpectedJarHash) {
    throw 'Only the exact legacy BC 1.83 artifact may generate these synthetic fixtures.'
}
$taskWork = Join-Path $taskRepo ('.tooling/dependency-review/bc-fixture-generation/' + [Guid]::NewGuid().ToString())
$taskClasses = Join-Path $taskWork 'classes'
New-Item -ItemType Directory -Path $taskClasses -Force | Out-Null
& (Join-Path $taskJdk 'bin/javac.exe') '-cp' $taskLegacyJar '-d' $taskClasses $taskProbeSource
if ($LASTEXITCODE -ne 0) { throw 'Legacy fixture probe compilation failed.' }
Add-Type -AssemblyName System.IO.Compression.FileSystem
$taskAttachments = @(Get-Content -LiteralPath (Join-Path $taskResources 'attachments.json') -Raw -Encoding UTF8 | ConvertFrom-Json)
$taskProperties = [Collections.Generic.List[string]]::new()
$taskProperties.Add('# TEST ONLY: all medical data and this password are synthetic and public.')
$taskProperties.Add('# Immutable ciphertext generated by the exact BC 1.83 JAR in a separate JVM.')
$taskProperties.Add('# HTBACKUP outer version 1, PBKDF2-HMAC-SHA256 210000, AES-256-GCM.')
$taskProperties.Add('# Deterministic salt/IV are ONLY for fixtures, never production backups.')
$taskProperties.Add('# Regenerate using scripts/generate-bc183-backup-fixtures.ps1 and the public plaintext resources.')
$taskProperties.Add('public.password=Synthetic-Backup-2026!')
$taskProperties.Add('generator.bcVersion=1.83')
$taskProperties.Add('generator.bcSha256=' + $taskExpectedJarHash)
for ($taskIndex = 0; $taskIndex -lt $taskAttachments.Count; $taskIndex++) {
    $taskBytes = [Convert]::FromBase64String($taskAttachments[$taskIndex].contentBase64)
    $taskSha = [Security.Cryptography.SHA256]::Create()
    try { $taskHash = [BitConverter]::ToString($taskSha.ComputeHash($taskBytes)).Replace('-', '').ToLowerInvariant() }
    finally { $taskSha.Dispose() }
    $taskProperties.Add('attachment.' + ($taskIndex + 1) + '.sha256=' + $taskHash)
}
for ($taskVersion = 1; $taskVersion -le 5; $taskVersion++) {
    $taskZipPath = Join-Path $taskWork ('v' + $taskVersion + '.zip')
    $taskCipherPath = Join-Path $taskWork ('v' + $taskVersion + '.encrypted')
    $taskVerifyPath = Join-Path $taskWork ('v' + $taskVersion + '.verified.zip')
    $taskPaths = [Collections.Generic.List[string]]::new()
    $taskArchive = [IO.Compression.ZipFile]::Open($taskZipPath, [IO.Compression.ZipArchiveMode]::Create)
    try {
        $taskEntry = $taskArchive.CreateEntry('manifest.json', [IO.Compression.CompressionLevel]::Optimal)
        $taskEntry.LastWriteTime = [DateTimeOffset]::new(2000, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
        $taskDestination = $taskEntry.Open()
        $taskSource = [IO.File]::OpenRead((Join-Path $taskResources ('v' + $taskVersion + '-manifest.json')))
        try { $taskSource.CopyTo($taskDestination) } finally { $taskSource.Dispose(); $taskDestination.Dispose() }
        foreach ($taskAttachment in $taskAttachments) {
            $taskArchivePath = if ($taskVersion -eq 1) { 'files/' + $taskAttachment.legacyId } else { 'files/' + $taskAttachment.uuid }
            $taskPaths.Add($taskArchivePath)
            $taskEntry = $taskArchive.CreateEntry($taskArchivePath, [IO.Compression.CompressionLevel]::Optimal)
            $taskEntry.LastWriteTime = [DateTimeOffset]::new(2000, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
            $taskDestination = $taskEntry.Open()
            try {
                $taskBytes = [Convert]::FromBase64String($taskAttachment.contentBase64)
                $taskDestination.Write($taskBytes, 0, $taskBytes.Length)
            } finally { $taskDestination.Dispose() }
        }
    } finally { $taskArchive.Dispose() }
    $taskClasspath = $taskClasses + [IO.Path]::PathSeparator + $taskLegacyJar
    & (Join-Path $taskJdk 'bin/java.exe') '-Xmx32m' '-cp' $taskClasspath 'com.healthtimeline.app.backup.LegacyBackupCryptoProbe' 'fixture' $taskZipPath $taskCipherPath $taskVersion
    if ($LASTEXITCODE -ne 0) { throw 'Legacy fixture encryption failed.' }
    & (Join-Path $taskJdk 'bin/java.exe') '-Xmx32m' '-cp' $taskClasspath 'com.healthtimeline.app.backup.LegacyBackupCryptoProbe' 'decrypt' $taskCipherPath $taskVerifyPath
    if ($LASTEXITCODE -ne 0) { throw 'Legacy fixture verification failed.' }
    $taskPlainHash = (Get-FileHash -LiteralPath $taskZipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    if ((Get-FileHash -LiteralPath $taskVerifyPath -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskPlainHash) { throw 'Legacy fixture verification bytes differ.' }
    $taskProperties.Add('v' + $taskVersion + '.plaintextSha256=' + $taskPlainHash)
    $taskProperties.Add('v' + $taskVersion + '.containerSha256=' + (Get-FileHash -LiteralPath $taskCipherPath -Algorithm SHA256).Hash.ToLowerInvariant())
    $taskProperties.Add('v' + $taskVersion + '.attachmentPaths=' + ($taskPaths -join ','))
    $taskProperties.Add('v' + $taskVersion + '.containerBase64=' + [Convert]::ToBase64String([IO.File]::ReadAllBytes($taskCipherPath)))
}
# This is a mechanically generated, public golden test artifact; not a customer .htbackup.
[IO.File]::WriteAllLines((Join-Path $taskResources 'bc183-golden.properties'), $taskProperties, [Text.UTF8Encoding]::new($false))
Write-Output 'Generated and old-runtime-verified five public BC 1.83 golden backup fixtures.'

package com.healthtimeline.app.data

import android.content.Context
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.sqlite.db.SupportSQLiteDatabase
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import net.zetetic.database.sqlcipher.SupportOpenHelperFactory
import org.json.JSONArray
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.security.MessageDigest
import java.util.UUID

/** Requires baseline assets generated by scripts/test-sqlcipher-compat.sh, never customer data. */
@RunWith(AndroidJUnit4::class)
class EncryptedDatabaseCompatibilityTest {
    private lateinit var context: Context
    private lateinit var directory: File
    private val opened = mutableListOf<AppDatabase>()
    private val assets get() = InstrumentationRegistry.getInstrumentation().context.assets

    @Before fun setUp() {
        System.loadLibrary("sqlcipher")
        context = ApplicationProvider.getApplicationContext()
        directory = File(context.cacheDir, "synthetic-encrypted-compat-${UUID.randomUUID()}")
        check(directory.mkdirs())
        val marker = JSONObject(assets.open("seed-ready.json").bufferedReader().use { it.readText() })
        assertEquals("4.18.0", marker.getString("baselineArtifact"))
        assertEquals(8, marker.getInt("schemaVersion"))
        assertTrue(marker.getLong("walBytes") > 32L)
    }

    @After fun tearDown() {
        opened.forEach { it.close() }
        if (::directory.isInitialized) directory.deleteRecursively() // This test's unique synthetic directory only.
    }

    @Test fun actualRoomOpensOldClosedEncryptedDatabaseAndPreservesAllMedicalFields() = runBlocking {
        verifyFixture("closed")
    }

    @Test fun actualRoomRecoversOldCommittedWalWithoutLosingMedicalFields() = runBlocking {
        // A nonempty WAL alone is not proof that its committed pages are needed.
        // Open a separate main-file-only copy and require it NOT to reproduce the
        // complete old snapshot. Never remove or mutate the original fixture WAL.
        val missingWalDirectory = File(directory, "main-file-only").apply { check(mkdirs()) }
        val withoutWal = File(missingWalDirectory, "wal.db")
        assets.open("wal.db").use { input -> withoutWal.outputStream().use { input.copyTo(it) } }
        val missingWalDatabase = build(withoutWal)
        val completeWithoutWal = runCatching {
            assertSnapshot(missingWalDatabase.openHelper.writableDatabase, snapshot("wal"))
        }.isSuccess
        missingWalDatabase.close()
        assertFalse("The baseline WAL must contain required committed medical data", completeWithoutWal)
        verifyFixture("wal")
    }

    @Test fun wrongKeyCannotClearOrRewriteOldEncryptedDatabase() {
        val file = copyAsset("closed.db")
        val originalHash = hash(file)
        val wrong = build(file, "wrong-public-synthetic-test-key")
        assertTrue(runCatching { wrong.openHelper.writableDatabase }.isFailure)
        wrong.close()
        assertTrue("Wrong-key failure must not delete the old DB", file.isFile)
        assertEquals(originalHash, hash(file))
        val valid = build(file)
        assertIntegrity(valid.openHelper.writableDatabase)
        assertSnapshot(valid.openHelper.writableDatabase, snapshot("closed"))
    }

    private suspend fun verifyFixture(name: String) {
        val expected = snapshot(name)
        assertTrue(expected.getString("sourceEngine").startsWith("4.18.0"))
        val schemaBytes = assets.open("com.healthtimeline.app.data.AppDatabase/8.json").use { it.readBytes() }
        assertEquals(expected.getString("schemaSha256"), hash(schemaBytes))
        val file = copyAsset("$name.db")
        if (name == "wal") {
            val wal = copyAsset("wal.db-wal")
            assertTrue(wal.length() > 32)
            // SQLite rebuilds SHM from WAL; intentionally do not depend on a copied process-local SHM.
        } else {
            assertEquals(assets.open("closed.sha256").bufferedReader().use { it.readText().trim() }, hash(file))
        }
        val database = build(file)
        val sql = database.openHelper.writableDatabase
        assertTrue(scalar(sql, "PRAGMA cipher_version").startsWith("4.19.0"))
        assertEquals("8", scalar(sql, "PRAGMA user_version"))
        assertEquals("4096", scalar(sql, "PRAGMA cipher_page_size"))
        assertEquals("256000", scalar(sql, "PRAGMA kdf_iter"))
        assertEquals("wal", scalar(sql, "PRAGMA journal_mode").lowercase())
        assertEquals("2", scalar(sql, "PRAGMA synchronous"))
        assertIntegrity(sql)
        assertSnapshot(sql, expected)

        // Exercise actual generated Room DAOs, not only raw SQL and a fake schema.
        val tables = expected.getJSONObject("tables")
        assertEquals(rowCount(tables, "family_members"), database.familyMemberDao().all().size)
        assertEquals(rowCount(tables, "conditions"), database.conditionDao().all().size)
        assertEquals(rowCount(tables, "clinical_records"), database.clinicalRecordDao().all().size)
        assertEquals(rowCount(tables, "attachments"), database.attachmentDao().all().size)
        assertEquals(rowCount(tables, "follow_up_schedules"), database.followUpDao().allSchedules().size)
        assertEquals(rowCount(tables, "follow_up_occurrences"), database.followUpDao().allOccurrences().size)
        assertEquals(rowCount(tables, "medications"), database.medicationDao().allMedications().size)
        assertEquals(rowCount(tables, "medication_schedules"), database.medicationDao().allSchedules().size)
        assertEquals(rowCount(tables, "medication_logs"), database.medicationDao().allLogs().size)
        val records = database.clinicalRecordDao().all()
        assertTrue(records.any { it.deletedAt != null })
        assertTrue(database.medicationDao().allMedications().any { it.endedAt != null })
        val files = expected.getJSONObject("files")
        files.keys().forEach { path -> assertEquals(files.getString(path), hash(copyAsset(path))) }

        val first = records.first()
        database.clinicalRecordDao().update(first.copy(title = "虚构兼容测试写入"))
        database.close()
        val reopened = build(file)
        assertEquals("虚构兼容测试写入", reopened.clinicalRecordDao().byId(first.id)?.title)
        reopened.clinicalRecordDao().update(first)
        assertSnapshot(reopened.openHelper.writableDatabase, expected)
        assertIntegrity(reopened.openHelper.writableDatabase)
    }

    private fun build(file: File, password: String = PUBLIC_PASSWORD): AppDatabase =
        Room.databaseBuilder(context, AppDatabase::class.java, file.absolutePath)
            .openHelperFactory(SupportOpenHelperFactory(password.toByteArray(Charsets.UTF_8)))
            .addMigrations(AppDatabase.MIGRATION_1_2, AppDatabase.MIGRATION_2_3, AppDatabase.MIGRATION_3_4,
                AppDatabase.MIGRATION_4_5, AppDatabase.MIGRATION_5_6, AppDatabase.MIGRATION_6_7, AppDatabase.MIGRATION_7_8)
            .setJournalMode(RoomDatabase.JournalMode.WRITE_AHEAD_LOGGING)
            .addCallback(object : RoomDatabase.Callback() {
                override fun onOpen(db: SupportSQLiteDatabase) { db.execSQL("PRAGMA synchronous=FULL") }
            }).build().also { opened += it }

    private fun assertSnapshot(db: SupportSQLiteDatabase, expected: JSONObject) {
        val tables = expected.getJSONObject("tables")
        tables.keys().forEach { table ->
            assertEquals("All original fields in $table", tables.getJSONObject(table).toString(),
                query(db, "SELECT * FROM `$table` ORDER BY id").toString())
        }
        assertEquals("Schema, indexes and foreign keys", expected.getJSONObject("schema").toString(),
            query(db, "SELECT type,name,tbl_name,sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' ORDER BY type,name").toString())
    }

    private fun assertIntegrity(db: SupportSQLiteDatabase) {
        assertEquals("ok", scalar(db, "PRAGMA quick_check"))
        db.query("PRAGMA cipher_integrity_check").use { assertFalse("Encrypted page authentication failed", it.moveToFirst()) }
        db.query("PRAGMA foreign_key_check").use { assertFalse("Invalid foreign keys", it.moveToFirst()) }
    }

    private fun query(db: SupportSQLiteDatabase, statement: String): JSONObject {
        val columns = JSONArray()
        val rows = JSONArray()
        db.query(statement).use { cursor ->
            cursor.columnNames.forEach { columns.put(it) }
            while (cursor.moveToNext()) {
                rows.put(JSONArray().apply {
                    for (column in 0 until cursor.columnCount) put(if (cursor.isNull(column)) JSONObject.NULL else cursor.getString(column))
                })
            }
        }
        return JSONObject().put("columns", columns).put("rows", rows)
    }

    private fun scalar(db: SupportSQLiteDatabase, sql: String): String = db.query(sql).use {
        check(it.moveToFirst()); it.getString(0)
    }
    private fun snapshot(name: String) = JSONObject(assets.open("$name.snapshot.json").bufferedReader().use { it.readText() })
    private fun rowCount(tables: JSONObject, table: String) = tables.getJSONObject(table).getJSONArray("rows").length()
    private fun copyAsset(name: String): File = File(directory, name).also { file ->
        check(file.canonicalPath.startsWith(directory.canonicalPath + File.separator))
        file.parentFile?.mkdirs()
        assets.open(name).use { input -> file.outputStream().use { input.copyTo(it) } }
    }
    private fun hash(file: File) = file.inputStream().use { input ->
        val digest = MessageDigest.getInstance("SHA-256")
        val buffer = ByteArray(8192)
        while (true) { val count = input.read(buffer); if (count < 0) break; digest.update(buffer, 0, count) }
        digest.digest().joinToString("") { "%02x".format(it) }
    }
    private fun hash(bytes: ByteArray) = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    companion object {
        private const val PUBLIC_PASSWORD = "public-synthetic-sqlcipher-compat-key-not-for-real-data"
    }
}
